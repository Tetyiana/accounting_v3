// Перетворення імені на кличний відмінок (вокатив) для звертань.
// Правила: ПКМ №1.4.2 та ДСТУ 8302:2015.

export const toVocative = (fullName) => {
  if (!fullName) return '';
  // Беремо перше слово (ім'я) або перше слово у форматі "Ім'я"
  const parts = fullName.trim().split(/\s+/);
  // Якщо рядок виглядає як "Прізвище Ім'я" (типово для ФОП),
  // спробуємо знайти ім'я (друге слово); якщо одне слово — беремо його
  const firstName = parts.length >= 2 ? parts[1] : parts[0];
  if (!firstName) return fullName;
  return vocativeSingle(firstName);
};

const vocativeSingle = (name) => {
  const n = name;

  // ─── Жіночі імена ─────────────────────────────────────────────
  // -ія → -іє (Марія → Маріє, Юлія → Юліє, Надія → Надіє, Лія → Ліє)
  if (n.endsWith('ія')) return n.slice(0, -2) + 'іє';
  // -яя → рідко, пропускаємо
  // -я → -ю (Наталя → Наталю, Уляна... ні, Уляна кінчається на -а)
  if (n.endsWith('я') && !n.endsWith('ья')) return n.slice(0, -1) + 'ю';
  // -а → -о (Тетяна → Тетяно, Ольга → Ольго, Леся → Лесю... ні, Леся кінчається на -я)
  if (n.endsWith('а')) return n.slice(0, -1) + 'о';

  // ─── Чоловічі імена ───────────────────────────────────────────
  // -й → -ю (Василій → Василію, Юрій → Юрію, Сергій → Сергію)
  if (n.endsWith('й')) return n.slice(0, -1) + 'ю';
  // -о → без змін (Микола... ні, Микола → Миколо через -а)
  // -о вже є кличний (Дем'яно, Добрило)
  if (n.endsWith('о')) return n;
  // м'який знак → -ю (Ігор... ні)
  // приголосний → +е (Іван → Іване, Олег → Олеже)
  const lastChar = n[n.length - 1].toLowerCase();
  if (!'аеєиіїоуюя'.includes(lastChar)) return n + 'е';

  return n; // якщо не підпало під правила — без змін
};
